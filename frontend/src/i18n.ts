// The languages every Movora client ships — keep in sync with the webOS and Android
// apps' LANGS so a title reads the same wherever you open it.
export const LANGS = ["hu", "en", "de", "fr", "es", "it", "ja"] as const;
export type Lang = (typeof LANGS)[number];

const translations: Record<Lang, typeof en> = { hu, en, de, fr, es, it, ja };

const stored = localStorage.getItem("movora.lang");
const detected = LANGS.find((code) => navigator.language.toLowerCase().startsWith(code));

void i18n.use(initReactI18next).init({
  resources: Object.fromEntries(
    LANGS.map((code) => [code, { translation: translations[code] }]),
  ),
  lng: stored ?? detected ?? "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export default i18n;
